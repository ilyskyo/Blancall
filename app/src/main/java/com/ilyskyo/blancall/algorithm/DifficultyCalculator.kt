    private fun buildStrokeMapFromCompact(compact: String): Map<Char, Int> {
        val map = mutableMapOf<Char, Int>()
        compact.split(";").forEach { entry ->
            val parts = entry.split(":")
            if (parts.size == 2) {
                val strokes = parts[0].toIntOrNull() ?: return@forEach
                parts[1].forEach { ch -> map[ch] = strokes }
            }
        }
        return map
    }
