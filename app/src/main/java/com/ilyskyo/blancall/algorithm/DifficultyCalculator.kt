    fun calculateCharDifficulty(char: Char): Float {
        // 非中文字符（英文字母/数字/标点等）查笔画表无意义，直接给较低难度，避免抬升整句均值。
        // 含基本区与扩展A区汉字；扩展A区生僻字未收录笔画表时默认 10 画（偏高，符合其生僻特性）。
        if (char !in '\u4e00'..'\u9fff' && char !in '\u3400'..'\u4dbf') return 0.2f
        val strokeScore = getStrokeScore(char)
        val rarityScore = getRarityScore(char)
        return (strokeScore * 0.7f + rarityScore * 0.3f).coerceIn(0f, 1f)
    }

    fun rankByDifficulty(
        chars: List<Char>,
        historyMistakes: Set<Char> = emptySet()
    ): List<Pair<Char, Float>> {
        return chars
            .map { ch ->
                var d = calculateCharDifficulty(ch)
                if (ch in historyMistakes) d = (d + 0.5f).coerceAtMost(1f)
                ch to d
            }
            .sortedByDescending { it.second }
    }

    private fun getStrokeScore(ch: Char): Float {
        val strokes = STROKE_MAP[ch] ?: 10
        return (strokes / MAX_STROKES).toFloat().coerceIn(0f, 1f)
    }

    // 生僻程度评分：刻意保持粗粒度两档（高频常用字 0.1 / 其余 0.5），
    // 简单可控；如需更细可在此扩展为三档，但当前粒度已满足难度排序需求。
    private fun getRarityScore(ch: Char): Float {
        return if (ch in HIGH_FREQ_CHARS) 0.1f else 0.5f
    }

